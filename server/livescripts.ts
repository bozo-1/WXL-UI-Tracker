                    // mix: most are genuine objective markers in this dataset, but a
                    // subset are turn-in markers that sit AT the giver. For an
                    // incomplete quest the turn-in marker must never win, so reject
                    // any 4+ row within 200 units of the giver coords.
                    if (objIdx >= 4 && (gx != 0.0 || gy != 0.0))
                    {
                        let ddx = px - gx;
                        let ddy = py - gy;
                        if (ddx * ddx + ddy * ddy < 200.0 * 200.0) continue;
                    }
