    function SendCorpsePosition(player: TSPlayer, x: number, y: number, z: number)
    {
        try
        {
            let pkt = CreateCustomPacket(300, 28);
            pkt.WriteUInt32(1);
            pkt.WriteDouble(x);
            pkt.WriteDouble(y);
            pkt.WriteDouble(z);
            pkt.SendToPlayer(player);
        }
        catch (e) {}
    }

    function ClearCorpsePosition(player: TSPlayer)
    {
        try
        {
            let pkt = CreateCustomPacket(300, 4);
            pkt.WriteUInt32(0);
            pkt.SendToPlayer(player);
        }
        catch (e) {}
    }

    events.Player.OnLogin((player: TSPlayer, firstLogin: bool) =>
    {
        try
        {
            if (player.IsDead())
            {
                let corpse = player.GetCorpse();
                if (corpse) SendCorpsePosition(player, corpse.GetX(), corpse.GetY(), corpse.GetZ());
            }
        }
        catch (e) {}
    });
