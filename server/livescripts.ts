    // Finds kill objective entries for a quest by reading RequiredNpcOrGo1-4
    // from quest_template. TSWoW populates these fields when quests are created.
    function GetQuestKillEntries(questId: number): number[]
    {
        let entries: number[] = [];

        // 1. Read RequiredNpcOrGo1-4 (direct kill objectives)
        try
        {
            let qr = QueryWorld(
                'SELECT RequiredNpcOrGo1,RequiredNpcOrGo2,RequiredNpcOrGo3,RequiredNpcOrGo4 FROM quest_template WHERE ID = ' + questId
            );
            if (qr && qr.GetRow())
            {
                for (let slot = 0; slot < 4; ++slot)
                {
                    let raw = qr.GetUInt32(slot) as number;
                    let value: number = raw > 0x7FFFFFFF ? raw - 0x100000000 : raw;
                    if (value > 0) entries.push(value);
                }
            }
        }
        catch (e) {}

        // 2. ItemDrop — creatures that drop required quest items (e.g. Defias Bandanas).
        //    Some quests declare drops in ItemDrop1-4; others use the classic
        //    RequiredItemId1-6 columns (handled in branch 3 below). Check both.
        try
        {
            let iq = QueryWorld(
                'SELECT DISTINCT clt.entry FROM creature_loot_template clt ' +
                'JOIN quest_template qt ON (' +
                '  clt.item = qt.ItemDrop1 OR clt.item = qt.ItemDrop2 OR ' +
                '  clt.item = qt.ItemDrop3 OR clt.item = qt.ItemDrop4) ' +
                'WHERE qt.ID = ' + questId + ' AND clt.item > 0 LIMIT 4'
            );
            while (iq && iq.GetRow())
            {
                let e = iq.GetUInt32(0) as number;
                if (e > 0 && entries.indexOf(e) === -1)
                    entries.push(e);
            }
        }
        catch (e) {}

        // 3. RequiredItemId1-6 — the items the quest actually requires (e.g. Red
        //    Burlap Bandana 752 for "Brotherhood of Thieves"). Resolve the
        //    creatures that drop them via creature_loot_template (indirect kill).
        try
        {
            let ri = QueryWorld(
                'SELECT RequiredItemId1,RequiredItemId2,RequiredItemId3,RequiredItemId4,RequiredItemId5,RequiredItemId6 FROM quest_template WHERE ID = ' + questId
            );
            let itemIds: number[] = [];
            if (ri && ri.GetRow())
            {
                for (let slot = 0; slot < 6; ++slot)
                {
                    let v = ri.GetUInt32(slot) as number;
                    if (v > 0) itemIds.push(v);
                }
            }
            if (itemIds.length > 0)
            {
                let iq = QueryWorld(
                    'SELECT DISTINCT clt.entry FROM creature_loot_template clt ' +
                    'WHERE clt.item IN (' + itemIds.join(',') + ') AND clt.item > 0 LIMIT 4'
                );
                while (iq && iq.GetRow())
                {
                    let e = iq.GetUInt32(0) as number;
                    if (e > 0 && entries.indexOf(e) === -1)
                        entries.push(e);
                }
            }
        }
        catch (e) {}

        return entries;
    }

