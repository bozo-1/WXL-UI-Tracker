                    // different continent than the player. Cross-continent rows
                    // (e.g. a Westfall quest's page while standing in Kalimdor)
                    // must never supply coordinates for the current zone - the
                    // quest then falls through to the map-filtered objective
                    // queries below (which use `AND map = pmap`).
                    if (kWorldMapAreaIdToMapId[wmaId] !== playerMapId) continue;
                    if (fx == 0.0 && fy == 0.0) { fx = px; fy = py; }
